"use client";
import { useEffect, useState } from "react";
import { Check, Inbox, Mail } from "lucide-react";
import { api, useLive } from "@/components/Live";
import { ago } from "@/components/ui";

// Which senders are clients and which are newsletters. Nothing here deletes anything: a sender filed
// under Updates still has its whole thread, it just leaves the client inbox and the reminders alone.

interface Thread {
  id: string;
  name: string;
  external_id: string;
  bulk: boolean;
  replies: number;
  msgs: number;
  last_at: number | null;
  suggest: boolean;
}

export default function MailFilter() {
  const { toast, refresh } = useLive();
  const [threads, setThreads] = useState<Thread[] | null>(null);
  const [lists, setLists] = useState<{ always: string[]; never: string[] }>({ always: [], never: [] });
  const [busy, setBusy] = useState(false);

  const load = () =>
    api<{ threads: Thread[]; lists: { always: string[]; never: string[] } }>("/api/mail-filter")
      .then((r) => (setThreads(r.threads ?? []), setLists(r.lists ?? { always: [], never: [] })))
      .catch(() => setThreads([]));
  useEffect(() => {
    load();
  }, []);

  const suggested = (threads ?? []).filter((t) => t.suggest);
  const filed = (threads ?? []).filter((t) => t.bulk);
  const clients = (threads ?? []).filter((t) => !t.bulk && !t.suggest);

  const tidy = async () => {
    setBusy(true);
    try {
      const r = await api<{ moved: number }>("/api/mail-filter", { action: "tidy", ids: suggested.map((t) => t.id) });
      toast(`Moved ${r.moved} ${r.moved === 1 ? "thread" : "threads"} to Updates`);
      await load();
      refresh();
    } catch (e) {
      toast(e instanceof Error ? e.message : "Failed", "error");
    } finally {
      setBusy(false);
    }
  };

  const move = async (t: Thread, toBulk: boolean) => {
    try {
      await api(`/api/conversations/${t.id}`, { action: "bulk", value: toBulk });
      await load();
      refresh();
    } catch (e) {
      toast(e instanceof Error ? e.message : "Failed", "error");
    }
  };

  const Row = ({ t, right }: { t: Thread; right: React.ReactNode }) => (
    <div className="flex flex-wrap items-center gap-x-3 gap-y-1 py-2">
      <span className="min-w-[220px] flex-1 truncate text-[13.5px]">
        {t.name === t.external_id ? t.external_id : `${t.name} · ${t.external_id}`}
      </span>
      <span className="tnum shrink-0 text-[12px] text-[var(--muted)]">
        {t.msgs} msg{t.msgs === 1 ? "" : "s"}
        {t.replies > 0 && ` · you replied`}
        {t.last_at ? ` · ${ago(t.last_at)}` : ""}
      </span>
      <span className="shrink-0">{right}</span>
    </div>
  );

  return (
    <div className="card px-5 py-2">
      <p className="py-3 text-[13px] text-[var(--ink-2)]">
        New mail is filed automatically: anything sent to a mailing list, generated by a machine, or coming from a no-reply address goes to{" "}
        <b>Updates</b> in the inbox. Nothing is deleted, and a sender you have ever replied to is never filed.
      </p>

      {threads === null && <p className="pb-3 text-[13px] text-[var(--muted)]">Loading…</p>}

      {!!suggested.length && (
        <div className="mb-3 rounded-xl border border-[var(--line)] bg-[var(--bg)] p-3">
          <div className="mb-1 flex flex-wrap items-center gap-2">
            <Mail size={14} className="text-[var(--ink-2)]" />
            <span className="text-[13.5px] font-medium">{suggested.length} already in your inbox look like service mail</span>
            <button className="btn btn-dark btn-sm ml-auto" disabled={busy} onClick={tidy}>
              Move them all to Updates
            </button>
          </div>
          <p className="mb-1 text-[12.5px] text-[var(--muted)]">You have never replied to any of these. Each one can be moved back afterwards.</p>
          <div className="divide-y divide-[var(--line)]">
            {suggested.map((t) => (
              <Row key={t.id} t={t} right={<button className="btn btn-ghost btn-sm" onClick={() => move(t, true)}>Move</button>} />
            ))}
          </div>
        </div>
      )}

      {!!filed.length && (
        <details className="mb-2">
          <summary className="cursor-pointer py-2 text-[13.5px]">
            <Inbox size={13} className="mr-1 inline" />
            Filed under Updates · {filed.length}
          </summary>
          <div className="divide-y divide-[var(--line)]">
            {filed.map((t) => (
              <Row key={t.id} t={t} right={<button className="btn btn-ghost btn-sm" onClick={() => move(t, false)}>It&apos;s a real email</button>} />
            ))}
          </div>
        </details>
      )}

      {!!clients.length && (
        <details>
          <summary className="cursor-pointer py-2 text-[13.5px]">
            <Check size={13} className="mr-1 inline text-[var(--green)]" />
            Treated as people · {clients.length}
          </summary>
          <div className="divide-y divide-[var(--line)]">
            {clients.map((t) => (
              <Row key={t.id} t={t} right={<button className="btn btn-ghost btn-sm" onClick={() => move(t, true)}>File under Updates</button>} />
            ))}
          </div>
        </details>
      )}

      {(lists.always.length > 0 || lists.never.length > 0) && (
        <p className="border-t border-[var(--line)] py-3 text-[12px] text-[var(--muted)]">
          Remembered: {lists.always.length} always a client, {lists.never.length} always Updates. Moving a thread either way updates this.
        </p>
      )}
    </div>
  );
}
